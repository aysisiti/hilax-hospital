// admin-users: account management for HR/Admin only.
// Actions (POST JSON): create_user, set_active, reset_password.
// Runs with the service key on the server; the browser never sees it.
// All input is validated here, and the caller must be an active hr_admin.
import { createClient } from "npm:@supabase/supabase-js@2";

const ALLOWED_ORIGINS = ["https://aysisiti.github.io"];
const ROLES = ["hr_admin", "physician", "nurse", "pharmacist", "medtech", "radtech", "patient"];
const SEXES = ["male", "female", "other"];
const PATIENT_EMAIL_DOMAIN = "patients.hilax.local"; // internal login address, never shown
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/;
const CONTROL_RE = /[\u0000-\u001f\u007f]/;

function corsHeaders(origin: string): Record<string, string> {
  const h: Record<string, string> = {
    "Access-Control-Allow-Methods": "POST, OPTIONS",
    "Access-Control-Allow-Headers": "authorization, content-type, apikey, x-client-info",
    "Vary": "Origin",
  };
  if (ALLOWED_ORIGINS.includes(origin)) h["Access-Control-Allow-Origin"] = origin;
  return h;
}

function json(body: unknown, status: number, cors: Record<string, string>): Response {
  return new Response(JSON.stringify(body), {
    status,
    headers: { ...cors, "Content-Type": "application/json", "Cache-Control": "no-store" },
  });
}

// Trimmed single-line text within length limits, or null if invalid.
function text(v: unknown, min: number, max: number): string | null {
  if (typeof v !== "string") return null;
  const s = v.replace(/\s+/g, " ").trim();
  if (s.length < min || s.length > max || CONTROL_RE.test(s)) return null;
  return s;
}

function email(v: unknown): string | null {
  const s = text(v, 3, 254);
  if (!s || !EMAIL_RE.test(s)) return null;
  return s.toLowerCase();
}

// 12-character temporary password without look-alike characters.
function tempPassword(): string {
  const alphabet = "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789";
  const limit = 256 - (256 % alphabet.length);
  let out = "";
  while (out.length < 12) {
    const buf = new Uint8Array(24);
    crypto.getRandomValues(buf);
    for (const b of buf) {
      if (b < limit && out.length < 12) out += alphabet[b % alphabet.length];
    }
  }
  return out;
}

type Admin = ReturnType<typeof createClient>;

async function createUser(admin: Admin, actorId: string, b: Record<string, unknown>) {
  const role = typeof b.role === "string" ? b.role : "";
  if (!ROLES.includes(role)) return { status: 400, body: { error: "Invalid role" } };
  const fullName = text(b.full_name, 1, 120);
  if (!fullName) return { status: 400, body: { error: "Invalid name" } };

  const password = tempPassword();

  if (role === "patient") {
    const age = b.age;
    if (typeof age !== "number" || !Number.isInteger(age) || age < 0 || age > 150) {
      return { status: 400, body: { error: "Invalid age" } };
    }
    const sex = typeof b.sex === "string" ? b.sex : "";
    if (!SEXES.includes(sex)) return { status: 400, body: { error: "Invalid sex" } };
    const address = text(b.address, 1, 300);
    if (!address) return { status: 400, body: { error: "Invalid address" } };
    let contactEmail: string | null = null;
    if (b.email !== undefined && b.email !== null && b.email !== "") {
      contactEmail = email(b.email);
      if (!contactEmail) return { status: 400, body: { error: "Invalid email" } };
    }

    // 1) patient record (number is generated by the database)
    const { data: patient, error: pErr } = await admin
      .from("patients")
      .insert({ full_name: fullName, age, sex, address, created_by: actorId })
      .select("patient_id, patient_number")
      .single();
    if (pErr || !patient) {
      console.error("create_user patient insert failed:", pErr?.message);
      return { status: 500, body: { error: "Could not create account" } };
    }
    const undoPatient = () => admin.from("patients").delete().eq("patient_id", patient.patient_id);

    // 2) login (patient number is the visible login name)
    const authEmail = `${String(patient.patient_number).toLowerCase()}@${PATIENT_EMAIL_DOMAIN}`;
    const { data: created, error: aErr } = await admin.auth.admin.createUser({
      email: authEmail,
      password,
      email_confirm: true,
    });
    if (aErr || !created?.user) {
      console.error("create_user auth failed:", aErr?.message);
      await undoPatient();
      return { status: 500, body: { error: "Could not create account" } };
    }
    const userId = created.user.id;
    const undoAll = async () => {
      await admin.auth.admin.deleteUser(userId); // also removes the users row (cascade)
      await undoPatient();
    };

    // 3) profile + link
    const { error: uErr } = await admin.from("users").insert({
      id: userId,
      role_name: "patient",
      full_name: fullName,
      login_id: patient.patient_number,
      email: contactEmail,
      must_change_password: true,
      created_by: actorId,
    });
    if (uErr) {
      console.error("create_user profile failed:", uErr.message);
      await undoAll();
      return { status: 500, body: { error: "Could not create account" } };
    }
    const { error: lErr } = await admin
      .from("patients")
      .update({ user_id: userId })
      .eq("patient_id", patient.patient_id);
    if (lErr) {
      console.error("create_user link failed:", lErr.message);
      await undoAll();
      return { status: 500, body: { error: "Could not create account" } };
    }

    return {
      status: 200,
      body: {
        ok: true,
        user: { id: userId, role, full_name: fullName, login_id: patient.patient_number, number: patient.patient_number },
        temp_password: password,
      },
    };
  }

  // Staff / admin account: logs in with email
  const staffEmail = email(b.email);
  if (!staffEmail) return { status: 400, body: { error: "Invalid email" } };

  const { data: created, error: aErr } = await admin.auth.admin.createUser({
    email: staffEmail,
    password,
    email_confirm: true,
  });
  if (aErr || !created?.user) {
    console.error("create_user auth failed:", aErr?.message);
    const taken = aErr && ((aErr as { code?: string }).code === "email_exists" || aErr.status === 422);
    return taken
      ? { status: 409, body: { error: "Email already in use" } }
      : { status: 500, body: { error: "Could not create account" } };
  }
  const userId = created.user.id;

  const { data: profile, error: uErr } = await admin
    .from("users")
    .insert({
      id: userId,
      role_name: role,
      full_name: fullName,
      login_id: staffEmail,
      email: staffEmail,
      must_change_password: true,
      created_by: actorId,
    })
    .select("staff_number")
    .single();
  if (uErr || !profile) {
    console.error("create_user profile failed:", uErr?.message);
    await admin.auth.admin.deleteUser(userId);
    return { status: 500, body: { error: "Could not create account" } };
  }

  return {
    status: 200,
    body: {
      ok: true,
      user: { id: userId, role, full_name: fullName, login_id: staffEmail, number: profile.staff_number },
      temp_password: password,
    },
  };
}

async function setActive(admin: Admin, actorId: string, b: Record<string, unknown>) {
  const id = typeof b.user_id === "string" ? b.user_id : "";
  if (!UUID_RE.test(id) || typeof b.active !== "boolean") {
    return { status: 400, body: { error: "Invalid request" } };
  }
  if (id === actorId) return { status: 400, body: { error: "You cannot change your own account" } };

  const { data: target } = await admin.from("users").select("id, active").eq("id", id).maybeSingle();
  if (!target) return { status: 404, body: { error: "User not found" } };

  const { error: uErr } = await admin.from("users").update({ active: b.active }).eq("id", id);
  if (uErr) {
    console.error("set_active update failed:", uErr.message);
    return { status: 500, body: { error: "Could not update account" } };
  }
  const { error: aErr } = await admin.auth.admin.updateUserById(id, {
    ban_duration: b.active ? "none" : "876000h",
  });
  if (aErr) {
    console.error("set_active ban failed:", aErr.message);
    await admin.from("users").update({ active: target.active }).eq("id", id);
    return { status: 500, body: { error: "Could not update account" } };
  }
  return { status: 200, body: { ok: true } };
}

async function resetPassword(admin: Admin, actorId: string, b: Record<string, unknown>) {
  const id = typeof b.user_id === "string" ? b.user_id : "";
  if (!UUID_RE.test(id)) return { status: 400, body: { error: "Invalid request" } };
  if (id === actorId) return { status: 400, body: { error: "Use change password for your own account" } };

  const { data: target } = await admin.from("users").select("id").eq("id", id).maybeSingle();
  if (!target) return { status: 404, body: { error: "User not found" } };

  const password = tempPassword();
  const { error: aErr } = await admin.auth.admin.updateUserById(id, { password });
  if (aErr) {
    console.error("reset_password failed:", aErr.message);
    return { status: 500, body: { error: "Could not reset password" } };
  }
  await admin.from("users").update({ must_change_password: true }).eq("id", id);
  return { status: 200, body: { ok: true, temp_password: password } };
}

Deno.serve(async (req: Request) => {
  const cors = corsHeaders(req.headers.get("origin") ?? "");
  if (req.method === "OPTIONS") return new Response(null, { status: 204, headers: cors });
  if (req.method !== "POST") return json({ error: "Method not allowed" }, 405, cors);

  const url = Deno.env.get("SUPABASE_URL");
  const serviceKey = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY");
  if (!url || !serviceKey) return json({ error: "Server not configured" }, 500, cors);
  const admin = createClient(url, serviceKey, { auth: { persistSession: false, autoRefreshToken: false } });

  // Who is calling?
  const token = (req.headers.get("authorization") ?? "").replace(/^Bearer\s+/i, "").trim();
  if (!token) return json({ error: "Not signed in" }, 401, cors);
  const { data: auth, error: authErr } = await admin.auth.getUser(token);
  if (authErr || !auth?.user) return json({ error: "Not signed in" }, 401, cors);
  const actorId = auth.user.id;

  // Only an active HR/Admin may continue.
  const { data: me } = await admin.from("users").select("role_name, active").eq("id", actorId).maybeSingle();
  if (!me || !me.active || me.role_name !== "hr_admin") return json({ error: "Not allowed" }, 403, cors);

  // Read and check the request body.
  if (Number(req.headers.get("content-length") ?? 0) > 10_000) return json({ error: "Request too large" }, 413, cors);
  let body: Record<string, unknown>;
  try {
    const parsed = JSON.parse(await req.text());
    if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) throw new Error("not an object");
    body = parsed as Record<string, unknown>;
  } catch {
    return json({ error: "Invalid request" }, 400, cors);
  }

  try {
    let result;
    switch (body.action) {
      case "create_user":
        result = await createUser(admin, actorId, body);
        break;
      case "set_active":
        result = await setActive(admin, actorId, body);
        break;
      case "reset_password":
        result = await resetPassword(admin, actorId, body);
        break;
      default:
        result = { status: 400, body: { error: "Unknown action" } };
    }
    return json(result.body, result.status, cors);
  } catch (e) {
    console.error("admin-users unexpected error:", e instanceof Error ? e.message : String(e));
    return json({ error: "Something went wrong" }, 500, cors);
  }
});
